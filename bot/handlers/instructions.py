@router.message(F.text == "📖 Как работает бот")
async def btn_instructions(message: Message):
    """
    Обработчик кнопки "📖 Как работает бот".
    
    Показывает выбор роли: Менеджер или Производство.
    """
    await message.answer(
        "📖 <b>Как работает бот</b>\n\n"
        "Выберите вашу роль, чтобы увидеть подходящую инструкцию:",
        reply_markup=instructions_choice_kb()
    )


@router.callback_query(F.data == "instructions_manager")
async def show_manager_instructions(callback: CallbackQuery):
    """
    Показать инструкцию для менеджера.
    
    Отображает пошаговое руководство по:
    - Созданию КП
    - Работе с архивом
    - Отслеживанию статусов
    """
    try:
        await callback.answer()
    except:
        pass  # Игнорируем ошибку, если callback устарел
    
    await callback.message.edit_text(
        MANAGER_INSTRUCTION,
        reply_markup=instructions_back_kb()
    )


@router.callback_query(F.data == "instructions_production")
async def show_production_instructions(callback: CallbackQuery):
    """
    Показать инструкцию для производства.
    
    Отображает пошаговое руководство по:
    - Планированию производства
    - Работе с днями
    - Формированию отчётов
    """
    try:
        await callback.answer()
    except:
        pass  # Игнорируем ошибку, если callback устарел
    
    await callback.message.edit_text(
        PRODUCTION_INSTRUCTION,
        reply_markup=instructions_back_kb()
    )


@router.callback_query(F.data == "instructions_back_to_choice")
async def back_to_role_choice(callback: CallbackQuery):
    """
    Вернуться к выбору роли (Менеджер/Производство).
    
    Показывает снова меню выбора инструкции.
    """
    try:
        await callback.answer()
    except:
        pass  # Игнорируем ошибку, если callback устарел
    
    await callback.message.edit_text(
        "📖 <b>Как работает бот</b>\n\n"
        "Выберите вашу роль, чтобы увидеть подходящую инструкцию:",
        reply_markup=instructions_choice_kb()
    )


@router.callback_query(F.data == "instructions_back_to_menu")
async def back_to_main_menu(callback: CallbackQuery):
    """
    Вернуться в главное меню.
    
    Закрывает инструкции и показывает главное меню бота.
    """
    try:
        await callback.answer()
    except:
        pass  # Игнорируем ошибку, если callback устарел
    
    await callback.message.answer(
        "Главное меню:",
        reply_markup=main_menu_kb()
    )
