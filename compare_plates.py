# -*- coding: utf-8 -*-
"""
Сравнение плит «поступили в бот» и «из КП» по названию и количеству.
"""
import re
from collections import defaultdict


def parse_list(text: str, sep: str = "\t") -> dict[str, int]:
    """Парсит список вида 'Плиты ПБ 69-12-8п    20' -> {'Плиты ПБ 69-12-8п': 20}."""
    result: dict[str, int] = defaultdict(int)
    for line in text.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        # Количество — последнее число в строке
        parts = line.split()
        if not parts:
            continue
        try:
            qty = int(parts[-1])
        except ValueError:
            continue
        name = " ".join(parts[:-1])
        result[name] += qty
    return dict(result)


def normalize_name(name: str) -> str:
    """Нормализация для сопоставления: запятая/точка в числах, лишние пробелы."""
    # Убираем суффиксы типа " кос", " кос. рез", " 1 выб", " 2 выб", "+доб" для группировки
    n = re.sub(r"\s+(кос\.?\s*рез?|кос|1\s*выб|2\s*выб)\s*$", "", name, flags=re.I)
    n = re.sub(r"\+\s*доб\s*$", "", n, flags=re.I)
    n = re.sub(r"\s+", " ", n).strip()
    # Приводим запятую в десятичных к одному виду (точка)
    n = n.replace(",", ".")
    # Унифицируем 0.3 и 3.0 в размерах (разное написание одной позиции)
    n = re.sub(r"-\s*0\.3\s*-", "-3.0-", n)
    # Убираем .0 у целых размеров: 7.0 -> 7, 5.0 -> 5 (бот пишет 7,0, КП — 7)
    n = re.sub(r"-(\d+)\.0-", r"-\1-", n)
    n = re.sub(r"-(\d+)\.0(п|$)", r"-\1\2", n)
    return n


def denormalize_for_display(norm: str) -> str:
    """Обратно к виду с запятой для вывода."""
    return norm.replace(".", ",")


