def aggregate_by_normalized(rows: dict[str, int]) -> dict[str, int]:
    """Суммирует количество по нормализованному названию."""
    agg: dict[str, int] = defaultdict(int)
    for name, qty in rows.items():
        agg[normalize_name(name)] += qty
    return dict(agg)


def main() -> None:
    import sys
    import io
    if sys.platform == "win32":
        sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8")

    bot_raw = parse_list(BOT_PLATES)
    kp_raw = parse_list(KP_PLATES, sep="\t")

    bot_norm = aggregate_by_normalized(bot_raw)
    # В КП бывает 0.3 и 0,3 — нормализуем одинаково
    kp_norm = aggregate_by_normalized(kp_raw)

    all_names = sorted(set(bot_norm) | set(kp_norm))

    only_bot = []
    only_kp = []
    qty_ok = []
    qty_mismatch = []

    for name in all_names:
        b = bot_norm.get(name, 0)
        k = kp_norm.get(name, 0)
        if b and not k:
            only_bot.append((name, b))
        elif k and not b:
            only_kp.append((name, k))
        elif b == k:
            qty_ok.append((name, b))
        else:
            qty_mismatch.append((name, b, k))

    print("=" * 60)
    print("СРАВНЕНИЕ: плиты в боте vs плиты в КП")
    print("=" * 60)
    print()

    print("--- Совпадают по названию и количеству ---")
    for name, q in qty_ok:
        print(f"  {denormalize_for_display(name)}  —  {q}")
    print(f"Всего позиций: {len(qty_ok)}")
    print()

    print("--- Расхождение по количеству (название есть в обоих) ---")
    for name, b, k in qty_mismatch:
        print(f"  {denormalize_for_display(name)}  |  в боте: {b}  |  в КП: {k}  |  разница: {b - k:+d}")
    print(f"Всего позиций: {len(qty_mismatch)}")
    print()

    print("--- Только в боте (нет в КП или 0 в КП) ---")
    for name, b in only_bot:
        print(f"  {denormalize_for_display(name)}  —  {b}")
    print(f"Всего позиций: {len(only_bot)}")
    print()

    print("--- Только в КП (нет в боте или 0 в боте) ---")
    for name, k in only_kp:
        print(f"  {denormalize_for_display(name)}  —  {k}")
    print(f"Всего позиций: {len(only_kp)}")
    print()

    # Специальные пары: разное написание одной и той же плиты
    aliases = [
        ("25,4-3,0-8п", "25,4-0.3-8п"),
        ("42-3,0-8п", "42-0.3-8п"),
        ("45-7,0-6п", "45-7-6п"),
        ("37,9-9,0-8п", "37,9-9-8п"),
        ("42-9,0-8п", "42-9-8п+доб"),
        ("61,8-5,0-8п", "61,8-5-8п"),
        ("39,0-12-8п", "39,0-12-8п"),
        ("40,0-12-8п", "40,0-12-8п"),
    ]
    print("--- Возможные синонимы (разное написание) ---")
    for a, b in aliases:
        na = normalize_name("Плиты ПБ " + a.replace(".", ","))
        nb = normalize_name("Плиты ПБ " + b.replace(".", ","))
        q_bot = bot_norm.get(na, 0) + bot_norm.get(nb, 0)
        q_kp = kp_norm.get(na, 0) + kp_norm.get(nb, 0)
        if q_bot or q_kp:
            status = "OK" if q_bot == q_kp else f"РАЗНИЦА: бот {q_bot}, КП {q_kp}"
            print(f"  Бот: ПБ {a}  |  КП: ПБ {b}  ->  {status}")


if __name__ == "__main__":
    main()
