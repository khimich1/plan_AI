def normalize_name(raw: str) -> str:
    """Приводит название к ключу для сравнения: убираем суффиксы кос/выб/доб, нормализуем 7,0→7 и т.д."""
    s = raw.strip()
    # #region agent log (57/57,1: какой сырой текст в какой ключ попал)
    if '57' in s and '-12-8' in s:
        try:
            _log_path = _DEBUG_LOG_8E9428
            with open(_log_path, 'a', encoding='utf-8') as _f:
                _f.write(__import__('json').dumps({"sessionId": "8e9428", "hypothesisId": "H_compare_norm", "location": "compare_order_kp:normalize_name_input", "message": "57/57,1: raw name before norm", "data": {"raw": raw[:80]}, "timestamp": __import__("time").time() * 1000}, ensure_ascii=False) + "\n")
        except Exception:
            pass
        # #endregion
    # Суффиксы «1 выб»/«2 выб» — после них в заказе иногда нет «п» в конце; восстанавливаем для единообразия
    if ' выб' in s:
        s = re.sub(r'\s+[12]\s+выб\s*$', '', s).strip()
        if re.search(r'\d$', s) and not s.endswith('п'):
            s += 'п'
    # Длинные суффиксы первыми, чтобы не обрезать частично
    for suf in [' кос. рез', ' кос.', ' кос', '+доб']:
        if suf in s:
            s = s.replace(suf, '')
    s = s.strip()
    # Нормализация целых дециметров: 7,0→7, 9,0→9, 39,0→39, 40,0→40
    s = re.sub(r'\b7,0\b', '7', s)
    s = re.sub(r'\b9,0\b', '9', s)
    s = re.sub(r'\b39,0\b', '39', s)
    s = re.sub(r'\b40,0\b', '40', s)
    # 5,0 в середине (ширина) → 5 для единообразия с "61,8-5-8п"
    s = re.sub(r'-5,0-', '-5-', s)
    # #region agent log (57/57,1: ключ после нормализации)
    if '57' in s and '-12-8' in s:
        try:
            import os as _os
            _log_path = _DEBUG_LOG_8E9428
            with open(_log_path, 'a', encoding='utf-8') as _f:
                _f.write(__import__('json').dumps({"sessionId": "8e9428", "hypothesisId": "H_compare_norm", "location": "compare_order_kp:normalize_name_output", "message": "57/57,1: key after norm", "data": {"normalized_key": s[:80]}, "timestamp": __import__("time").time() * 1000}, ensure_ascii=False) + "\n")
        except Exception:
            pass
        # #endregion
    return s


def parse_block(text: str) -> list[tuple[str, int]]:
    """Парсит блок строк 'Название  количество' или 'Название\tчисло'. Возвращает список (название, qty)."""
    lines = [ln.strip() for ln in text.strip().splitlines() if ln.strip()]
    out = []
    for ln in lines:
        # Сначала пробуем: в конце число после пробелов/таба
        m = re.match(r'^(.+?)[\t\s]+(\d+)\s*$', ln)
        if m:
            name = m.group(1).strip()
            qty = int(m.group(2))
            out.append((name, qty))
        else:
            # Не распарсилось — логируем
            print(f"  [skip] {ln[:80]!r}", file=__import__('sys').stderr)
    return out


def aggregate(items: list[tuple[str, int]]) -> dict[str, int]:
    """Агрегирует по нормализованному имени."""
    agg = defaultdict(int)
    for raw_name, qty in items:
        key = normalize_name(raw_name)
        agg[key] += qty
    return dict(agg)


def main():
    order_items = parse_block(ORDER_RAW)
    kp_items = parse_block(KP_RAW)

    order_agg = aggregate(order_items)
    kp_agg = aggregate(kp_items)

    total_order = sum(order_agg.values())
    total_kp = sum(kp_agg.values())

    all_keys = sorted(set(order_agg) | set(kp_agg))

    print("=== 1. Общее количество ===")
    print(f"Заказ: {total_order}")
    print(f"КП:    {total_kp}")
    print(f"Разница: {total_kp - total_order}")
    print()

    print("=== 2. Расхождения по позициям (нормализованное название) ===")
    diffs = []
    for key in all_keys:
        o = order_agg.get(key, 0)
        k = kp_agg.get(key, 0)
        if o != k:
            diffs.append((key, o, k))
    if not diffs:
        print("Нет расхождений.")
    else:
        for key, o, k in diffs:
            print(f"  {key}: заказ {o}, КП {k}  (разница {k - o})")
    print()

    print("=== 3. Только в заказе (нет в КП или 0 в КП) ===")
    only_order = [k for k in all_keys if order_agg.get(k, 0) > 0 and kp_agg.get(k, 0) == 0]
    for k in only_order:
        print(f"  {k}: заказ {order_agg[k]}")
    print()

    print("=== 4. Только в КП (нет в заказе или 0 в заказе) ===")
    only_kp = [k for k in all_keys if kp_agg.get(k, 0) > 0 and order_agg.get(k, 0) == 0]
    for k in only_kp:
        print(f"  {k}: КП {kp_agg[k]}")
    print()

    # Специально: 42-12-8п
    print("=== 5. Позиция 42-12-8п ===")
    key42 = 'Плиты ПБ 42-12-8п'
    print(f"  Заказ: {order_agg.get(key42, 0)}, КП: {kp_agg.get(key42, 0)}")

    # Специально: 57 vs 57,1
    print("\n=== 6. Позиции 57-12-8п и 57,1-12-8п (проверка путаницы) ===")
    o_57 = order_agg.get('Плиты ПБ 57-12-8п', 0)
    o_571 = order_agg.get('Плиты ПБ 57,1-12-8п', 0)
    k_57 = kp_agg.get('Плиты ПБ 57-12-8п', 0)
    k_571 = kp_agg.get('Плиты ПБ 57,1-12-8п', 0)
    print(f"  Заказ:  57-12-8п = {o_57},  57,1-12-8п = {o_571}  (всего {o_57 + o_571})")
    print(f"  КП:     57-12-8п = {k_57},  57,1-12-8п = {k_571}  (всего {k_57 + k_571})")
    if k_571 == 0 and k_57 == 23 + 2:
        print("  Интерпретация: в КП строка «57-12-8п 23» скорее всего 57,1-12-8п. Тогда 57: заказ 2, КП 2; 57,1: заказ 23, КП 23.")


if __name__ == '__main__':
    main()
